import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { IMPORTED_POSTS } from '../src/data/importedPosts.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const outFile = path.join(root, 'src', 'data', 'postIndex.js')

const POST_INDEX = IMPORTED_POSTS.map((post) => ({
  slug: post.slug,
  title: post.title,
  category: post.category,
  date: post.date,
  readTime: post.readTime,
  cover: post.cover,
  excerpt: post.excerpt,
  sourceUrl: post.sourceUrl,
}))

const output = `// Generated by scripts/generate-post-index.mjs. Do not edit by hand.\n\nexport const POST_INDEX = ${JSON.stringify(POST_INDEX, null, 2)}\n`

fs.writeFileSync(outFile, output)
console.log(`Generated ${path.relative(root, outFile)} with ${POST_INDEX.length} posts.`)
